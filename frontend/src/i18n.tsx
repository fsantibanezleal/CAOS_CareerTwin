function interpolate(message: string, values: TranslationValues = {}): string {
  return message.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match))
}

function detectedLocale(): Locale {
  if (typeof window === 'undefined') return 'en'
  const stored = window.localStorage.getItem('ct-locale')
  if (stored === 'en' || stored === 'es') return stored
  return window.navigator.language.toLowerCase().startsWith('es') ? 'es' : 'en'
}

export function translate(locale: Locale, key: string, values?: TranslationValues): string {
  const message = locale === 'es' ? spanishMessages[key] ?? key : key
  return interpolate(message, values)
}

type I18nValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, values?: TranslationValues) => string
  plural: (count: number, singular: string, plural: string, values?: TranslationValues) => string
  formatDate: (value: string | Date, options?: Intl.DateTimeFormatOptions) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(() => initial ?? detectedLocale())
  useEffect(() => {
    if (initial) setLocaleState(initial)
  }, [initial])
  useEffect(() => {
    document.documentElement.lang = locale
    window.localStorage.setItem('ct-locale', locale)
  }, [locale])
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (key, values) => translate(locale, key, values),
    plural: (count, singular, plural, values) => translate(locale, count === 1 ? singular : plural, { count, ...values }),
    formatDate: (date, options) => new Intl.DateTimeFormat(locale === 'es' ? 'es-CL' : 'en-US', options).format(new Date(date)),
  }), [locale])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): I18nValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n requires I18nProvider')
  return context
}
